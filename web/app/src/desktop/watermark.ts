export const WATERMARK_TAG = 0x637f2fd9c43c6cffn;

export interface EmbeddedWatermark {
  credit: string;
  author: string;
  githubProfileUrl: string;
  githubRepoUrl: string;
  formatted: string;
  integrityValid: boolean;
}

const MASK_64 = 0xffffffffffffffffn;
const FNV_PRIME = 0x100000001b3n;

function rotl32(v: number, n: number): number {
  return ((v << n) | (v >>> (32 - n))) >>> 0;
}

function quarterRound(s: Uint32Array, a: number, b: number, c: number, d: number): void {
  s[a] = (s[a]! + s[b]!) >>> 0;
  s[d] = rotl32(s[d]! ^ s[a]!, 16);
  s[c] = (s[c]! + s[d]!) >>> 0;
  s[b] = rotl32(s[b]! ^ s[c]!, 12);
  s[a] = (s[a]! + s[b]!) >>> 0;
  s[d] = rotl32(s[d]! ^ s[a]!, 8);
  s[c] = (s[c]! + s[d]!) >>> 0;
  s[b] = rotl32(s[b]! ^ s[c]!, 7);
}

function readU32Le(buf: Uint8Array, off: number): number {
  return (buf[off]! | (buf[off + 1]! << 8) | (buf[off + 2]! << 16) | (buf[off + 3]! << 24)) >>> 0;
}

function assembleKey(shareA: Uint8Array, shareB: Uint8Array): Uint8Array {
  const key = new Uint8Array(32);
  for (let i = 0; i < 32; i++) {
    key[i] = (shareA[i] ?? 0) ^ (shareB[i] ?? 0);
  }
  return key;
}

function chacha20Block(key: Uint8Array, counter: number, nonce: Uint8Array): Uint8Array {
  const init = new Uint32Array([
    0x61707865,
    0x3320646e,
    0x79622d32,
    0x6b206574,
    readU32Le(key, 0),
    readU32Le(key, 4),
    readU32Le(key, 8),
    readU32Le(key, 12),
    readU32Le(key, 16),
    readU32Le(key, 20),
    readU32Le(key, 24),
    readU32Le(key, 28),
    counter >>> 0,
    readU32Le(nonce, 0),
    readU32Le(nonce, 4),
    readU32Le(nonce, 8),
  ]);
  const work = new Uint32Array(init);
  for (let i = 0; i < 10; i++) {
    quarterRound(work, 0, 4, 8, 12);
    quarterRound(work, 1, 5, 9, 13);
    quarterRound(work, 2, 6, 10, 14);
    quarterRound(work, 3, 7, 11, 15);
    quarterRound(work, 0, 5, 10, 15);
    quarterRound(work, 1, 6, 11, 12);
    quarterRound(work, 2, 7, 8, 13);
    quarterRound(work, 3, 4, 9, 14);
  }

  const out = new Uint8Array(64);
  for (let i = 0; i < 16; i++) {
    const val = (work[i]! + init[i]!) >>> 0;
    out[i * 4] = val & 0xff;
    out[i * 4 + 1] = (val >>> 8) & 0xff;
    out[i * 4 + 2] = (val >>> 16) & 0xff;
    out[i * 4 + 3] = (val >>> 24) & 0xff;
  }
  return out;
}

function chacha20Xor(key: Uint8Array, counterStart: number, nonce: Uint8Array, data: Uint8Array): Uint8Array {
  const out = new Uint8Array(data.length);
  for (let off = 0, blk = 0; off < data.length; off += 64, blk++) {
    const ks = chacha20Block(key, counterStart + blk, nonce);
    const end = Math.min(64, data.length - off);
    for (let i = 0; i < end; i++) {
      out[off + i] = data[off + i]! ^ ks[i]!;
    }
  }
  return out;
}

function computeIntegrityTag(key: Uint8Array, nonce: Uint8Array, plaintext: Uint8Array): bigint {
  // Derive auth key from block 0 so encryption starts at counter 1, matching RFC 8439 layout.
  const authKey = chacha20Block(key, 0, nonce);
  let h = 0xcbf29ce484222325n;
  for (const part of [authKey, nonce, plaintext]) {
    for (const b of part) {
      h ^= BigInt(b);
      h = (h * FNV_PRIME) & MASK_64;
    }
  }
  h ^= h >> 30n;
  h = (h * 0xbf58476d1ce4e5b9n) & MASK_64;
  h ^= h >> 27n;
  h = (h * 0x94d049bb133111ebn) & MASK_64;
  h ^= h >> 31n;
  return h;
}

function extractFormattedField(formatted: string, prefix: string): string {
  for (const line of formatted.split('\n')) {
    const trimmed = line.trimStart();
    if (!trimmed.startsWith(prefix)) continue;
    const colon = trimmed.indexOf(':');
    if (colon >= 0) {
      return trimmed.slice(colon + 1).trim();
    }
  }
  return '';
}

export function decodeWatermarkBytes(
  cipher: Uint8Array = ENCRYPTED_WATERMARK,
  expectedTag: bigint = WATERMARK_TAG,
  shareA: Uint8Array = KEY_SHARE_A,
  shareB: Uint8Array = KEY_SHARE_B,
  nonce: Uint8Array = WATERMARK_NONCE,
): EmbeddedWatermark {
  const key = assembleKey(shareA, shareB);
  const plain = chacha20Xor(key, 1, nonce, cipher);
  const integrityValid = computeIntegrityTag(key, nonce, plain) === expectedTag;
  const formatted = integrityValid ? new TextDecoder().decode(plain) : '';

  return {
    credit: extractFormattedField(formatted, 'Credit'),
    author: extractFormattedField(formatted, 'Developer'),
    githubProfileUrl: extractFormattedField(formatted, 'GitHub'),
    githubRepoUrl: extractFormattedField(formatted, 'Repository'),
    formatted,
    integrityValid,
  };
}

let cachedWatermark: EmbeddedWatermark | null = null;

export function getEmbeddedWatermark(): EmbeddedWatermark {
  cachedWatermark ??= decodeWatermarkBytes();
  return cachedWatermark;
}

export async function openExternalUrl(url: string): Promise<void> {
  if (isTauriDesktop()) {
    try {
      await openUrl(url);
      return;
    } catch {
      // Fall back to window.open if opener IPC fails outside packaged runtime.
    }
  }
  if (typeof window !== 'undefined') {
    window.open(url, '_blank', 'noopener,noreferrer');
  }
}
